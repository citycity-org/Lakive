#!/usr/bin/env node
/**
 * Lakive Supabase Seed Script
 *
 * Seeds city_indices and city_occupation_scores from the current static data.
 * Run once after applying supabase-schema.sql:
 *
 *   SUPABASE_URL=https://... SUPABASE_SERVICE_KEY=eyJ... node scripts/seed-supabase.js
 *
 * Or set vars in .env.local and run:
 *   node -r dotenv/config scripts/seed-supabase.js dotenv_config_path=.env.local
 *
 * Uses upsert (ON CONFLICT DO UPDATE) — safe to re-run.
 */

const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL
const SERVICE_KEY  = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SERVICE_KEY

if (!SUPABASE_URL || !SERVICE_KEY) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY')
  console.error('Run: node -r dotenv/config scripts/seed-supabase.js dotenv_config_path=.env.local')
  process.exit(1)
}

const headers = {
  'Content-Type': 'application/json',
  'apikey': SERVICE_KEY,
  'Authorization': `Bearer ${SERVICE_KEY}`,
  'Prefer': 'resolution=merge-duplicates',
}

async function upsert(table, rows) {
  const url = `${SUPABASE_URL}/rest/v1/${table}`
  const res = await fetch(url, {
    method: 'POST',
    headers,
    body: JSON.stringify(rows),
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Upsert ${table} failed: ${res.status} ${text}`)
  }
  console.log(`  ✓ ${table}: ${rows.length} rows upserted`)
}

