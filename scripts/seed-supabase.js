async function main() {
  console.log('Lakive Supabase Seed')
  console.log(`Target: ${SUPABASE_URL}`)
  console.log()

  console.log('Seeding city_indices...')
  await upsert('city_indices', CITY_INDICES)

  console.log('Seeding city_occupation_scores...')
  const scoreRows = []
  for (const [cityId, occs] of Object.entries(FIT_MATRIX)) {
    for (const [occId, fit] of Object.entries(occs)) {
      scoreRows.push({
        city_id:        cityId,
        occupation_id:  occId,
        score:          fit.score,
        hpi_years:      fit.hpi_years,
        rpi:            fit.rpi,
        eoi:            fit.eoi,
        data_version:   '2026-09',
      })
    }
  }
  // Supabase REST upsert in batches of 200
  for (let i = 0; i < scoreRows.length; i += 200) {
    await upsert('city_occupation_scores', scoreRows.slice(i, i + 200))
  }

  console.log()
  console.log('✅ Seed complete.')
  console.log(`   ${CITY_INDICES.length} cities in city_indices`)
  console.log(`   ${scoreRows.length} rows in city_occupation_scores`)
}

